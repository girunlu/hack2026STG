def resolve_lang(explicit: str | None, accept_language: str | None) -> str:
    """Validate an explicit ``lang`` value, else parse ``Accept-Language``, else default.

    Never raises — bad input silently falls back to ``"en"``.
    """
    if explicit:
        code = explicit.strip().lower()[:2]
        if code in LANGS:
            return code
    if accept_language:
        # Accept-Language: de-CH,de;q=0.9,en-US;q=0.8,en;q=0.7
        for part in accept_language.split(","):
            code = part.strip().split(";")[0].strip().lower()[:2]
            if code in LANGS:
                return code
    return DEFAULT_LANG


def t(key: str, lang: str = DEFAULT_LANG, **fmt: object) -> str:
    """Look up ``key`` in ``lang``, falling back ``de`` → ``en`` → the key itself.

    Format placeholders are best-effort: a missing key never raises, and a bad
    format field returns the unformatted template rather than crashing.
    """
    for candidate in (lang, DEFAULT_LANG):
        table = MESSAGES.get(candidate)
        if table and key in table:
            template = table[key]
            if fmt:
                try:
                    return template.format(**fmt)
                except (KeyError, IndexError, ValueError):
                    return template
            return template
    if fmt:
        try:
            return key.format(**fmt)
        except (KeyError, IndexError, ValueError):
            pass
    return key
