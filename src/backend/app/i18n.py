"""Internationalization — flat message catalogue, no dependencies.

The prototype speaks English by default and German on request. Every user-facing string
the backend emits lives in ``MESSAGES``; code calls :func:`t` with a dotted key and the
resolved language. Missing keys fall back ``de`` → ``en`` → the key itself so a typo
never crashes a response.
"""

from __future__ import annotations

LANGS = ("en", "de")
DEFAULT_LANG = "en"

MESSAGES: dict[str, dict[str, str]] = {
    "en": {},
    "de": {},
}


def _en(**pairs: dict[str, str]) -> None:
    MESSAGES["en"].update(pairs)


def _de(**pairs: dict[str, str]) -> None:
    MESSAGES["de"].update(pairs)


